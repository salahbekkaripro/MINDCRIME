CREATE TABLE IF NOT EXISTS partie (
    id VARCHAR(64) PRIMARY KEY,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE enquete (
    id VARCHAR(128) PRIMARY KEY,
    partie_id VARCHAR(64) NOT NULL REFERENCES partie(id),
    seed BIGINT NOT NULL,
    lieu_crime VARCHAR(32) NOT NULL,
    creneau_crime_ordre INT NOT NULL,
    creneau_crime_libelle VARCHAR(32) NOT NULL,
    coupable_id VARCHAR(32) NOT NULL,
    statut_unicite VARCHAR(32) NOT NULL
);

CREATE INDEX idx_enquete_partie ON enquete(partie_id);

CREATE TABLE enquete_suspect (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquete_id VARCHAR(128) NOT NULL REFERENCES enquete(id) ON DELETE CASCADE,
    suspect_code VARCHAR(32) NOT NULL,
    nom VARCHAR(128) NOT NULL,
    profil VARCHAR(128) NOT NULL
);

CREATE INDEX idx_enquete_suspect_enquete ON enquete_suspect(enquete_id);

CREATE TABLE enquete_indice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquete_id VARCHAR(128) NOT NULL REFERENCES enquete(id) ON DELETE CASCADE,
    indice_code VARCHAR(32) NOT NULL,
    type_indice VARCHAR(32) NOT NULL,
    suspect_id VARCHAR(32) NOT NULL,
    lieu_id VARCHAR(32) NOT NULL,
    creneau_ordre INT NOT NULL,
    creneau_libelle VARCHAR(32) NOT NULL,
    description VARCHAR(512) NOT NULL,
    visible BOOLEAN NOT NULL
);

CREATE INDEX idx_enquete_indice_enquete ON enquete_indice(enquete_id);